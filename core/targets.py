#!/usr/bin/env python3
"""Generated install targets: targets/claude/* and targets/codex/* (build output, gitignored, never edited by hand).

The content comes from the install functions in modules/tools/scripts/install.py (claude_block, settings_fragment, codex_agents_md), so
there is one source of truth. Every file carries `GENERATED by sox install from <sources>; hash=<sha256 of the body>`
(modules/tools/scripts/generated.py); `check` reports hand edits (hash mismatch) and stale files (sources changed since generation).

Used by `sox install` and modules/tools/scripts/install.py. Stdlib only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "modules" / "tools" / "scripts"))

import generated  # noqa: E402
import install  # noqa: E402

TARGET_NAMES = ("claude", "codex")


def _wanted(target: str | None) -> list[str]:
    enabled = [name for name in TARGET_NAMES if install.PREFS[name]]
    return [name for name in enabled if target in (None, name)]


def render(target: str | None = None) -> dict[str, str]:
    """Relative path under targets/ -> generated text, for the enabled agents (or just `target`)."""
    files: dict[str, str] = {}
    wanted = _wanted(target)
    if "claude" in wanted:
        files["claude/CLAUDE.md"] = install.claude_block() + "\n"
        if install.PREFS["merge_settings"]:
            fragment = generated.stamp_json(install.settings_fragment(sys.executable), ["claude/settings.json"])
            files["claude/settings.fragment.json"] = json.dumps(fragment, indent=2, ensure_ascii=False) + "\n"
        for agent in sorted((install.SOCRATEX / "claude" / "agents").glob("*.md")):
            text = agent.read_text(encoding="utf-8")
            files[f"claude/agents/{agent.name}"] = generated.stamp_frontmatter(text, [f"claude/agents/{agent.name}"])
    if "codex" in wanted:
        files["codex/AGENTS.md"] = install.codex_agents_md()
    return files


def generate(target: str | None = None, out: Path | None = None) -> list[str]:
    """Write the generated files under `out` (default targets/) and drop stale files of the same targets. Returns the written paths."""
    out = Path(out) if out else install.TARGETS
    files = render(target)
    for name in _wanted(target):
        for old in (out / name).rglob("*") if (out / name).is_dir() else []:
            if old.is_file() and old.relative_to(out).as_posix() not in files:
                old.unlink()
    for rel, text in files.items():
        path = out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return sorted(files)


def _state(rel: str, text: str) -> str:
    if rel.endswith(".json"):
        try:
            return generated.verify_json(json.loads(text))
        except ValueError:
            return "unmarked"
    return generated.verify(text)


def check(target: str | None = None, out: Path | None = None) -> list[str]:
    """Problems of the files under `out`: missing, hand-edited, stale, or not produced by the generator."""
    out = Path(out) if out else install.TARGETS
    files = render(target)
    problems = []
    for rel, expected in files.items():
        path = out / rel
        if not path.is_file():
            problems.append(f"{rel}: missing (run `sox install --plan` to generate targets/)")
            continue
        text = path.read_text(encoding="utf-8")
        state = _state(rel, text)
        if state == "unmarked":
            problems.append(f"{rel}: has no GENERATED marker")
        elif state == "hand-edited":
            problems.append(f"{rel}: hand-edited (the body no longer matches the marker hash); change the sources instead")
        elif text != expected:
            problems.append(f"{rel}: stale (sources changed since it was generated)")
    for name in _wanted(target):
        for path in sorted((out / name).rglob("*")) if (out / name).is_dir() else []:
            if path.is_file() and path.relative_to(out).as_posix() not in files:
                problems.append(f"{path.relative_to(out).as_posix()}: not produced by the generator (hand-added?)")
    return problems


def startup_bytes(target: str) -> int:
    """Bytes the startup text costs at session start: for Claude the block plus every @imported file, for Codex the inlined file."""
    if target == "codex":
        return len(install.codex_agents_md().encode("utf-8"))
    items = install.startup_items(install.CLAUDE_IMPORTS)
    return len(install.claude_block().encode("utf-8")) + sum((install.SOCRATEX / item).stat().st_size for item in items)
