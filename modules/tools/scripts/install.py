# While a plan is collected, write_if_changed also records (path, old text, new text) here.
PLAN: list[tuple[Path, str | None, str]] | None = None


def posix(path: Path) -> str:
    return path.as_posix()


# ---------- preferences and questions ----------

def detect_dirs() -> tuple[Path, Path]:
    """Config folders of the two agents: the vendor's own environment variable first, else the home default."""
    claude = Path(os.environ.get("CLAUDE_CONFIG_DIR") or HOME_DIR / ".claude")
    codex = Path(os.environ.get("CODEX_HOME") or HOME_DIR / ".codex")
    return claude, codex


def apply_prefs(prefs: dict) -> None:
    """Make prefs the active choice (also sets the config folders used by every installer step)."""
    global CLAUDE, CODEX
    PREFS.clear()
    PREFS.update(PREF_DEFAULTS)
    PREFS.update({key: prefs[key] for key in PREF_DEFAULTS if key in prefs})
    claude, codex = detect_dirs()
    CLAUDE = Path(PREFS["claude_dir"]) if PREFS["claude_dir"] else claude
    CODEX = Path(PREFS["codex_dir"]) if PREFS["codex_dir"] else codex


def load_prefs() -> dict | None:
    try:
        return json.loads(PREFS_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def save_prefs() -> None:
    LOCAL.mkdir(exist_ok=True)
    PREFS_FILE.write_text(json.dumps(PREFS, indent=2) + "\n", encoding="utf-8", newline="\n")


def ask(question: str, why: str, default: bool, auto: bool) -> bool:
    """Yes/no question with the reason shown. auto=True takes the recommended answer without asking."""
    if auto:
        return default
    print(f"\n{question}\n  Why: {why}")
    while True:
        answer = input(f"  [{'Y/n' if default else 'y/N'}] ").strip().lower()
        if not answer:
            return default
        if answer in ("y", "yes"):
            return True
        if answer in ("n", "no"):
            return False


def ask_text(question: str, default: str, auto: bool) -> str:
    if auto:
        return default
    return input(f"\n{question}\n  [{default}] ").strip() or default


def collect_prefs(auto: bool) -> dict:
    """The install wizard. Recommended answers follow what is detected on this machine."""
    claude_dir, codex_dir = detect_dirs()
    has_claude = claude_dir.exists() or shutil.which("claude") is not None
    has_codex = codex_dir.exists() or shutil.which("codex") is not None
    prefs = dict(PREF_DEFAULTS)
    if not auto:
        print("SocratexAI install: nothing is changed until you answer. Enter accepts the recommended answer.")
    prefs["claude_dir"] = ask_text("Claude Code config folder (auto-detected):", str(claude_dir), auto)
    prefs["codex_dir"] = ask_text("Codex config folder (auto-detected):", str(codex_dir), auto)
    prefs["claude"] = ask("Set up Claude Code?", "Adds the core rules and agents to your Claude config.",
                          has_claude or not has_codex, auto)
    prefs["codex"] = ask("Set up Codex?", "Generates Codex AGENTS.md and agent files from the same core rules.",
                         has_codex, auto)
    if prefs["claude"]:
        prefs["merge_settings"] = ask(
            "Merge SocratexAI settings into Claude's settings.json?",
            "Installs the guard hook (blocks destructive git, secret-file reads, big-ledger dumps) and deny rules for "
            "secrets. Your other keys are kept; a backup is made first. Without it the guard is NOT active.", True, auto)
        prefs["codex_plugin"] = prefs["merge_settings"] and ask(
            "Enable the OpenAI Codex plugin in Claude Code?",
            "Adds /codex:review and /codex:rescue (second opinion, delegation). Needs Codex installed; skip if unused.",
            has_codex, auto)
        prefs["flow_panel"] = prefs["merge_settings"] and ask(
            "Enable the flow-panel mod (live session cost view)?",
            "Optional local UI for session usage. Sets CLAUDE_CODE_PLUGIN_DIRS in settings.json.", False, auto)
    else:
        prefs.update(merge_settings=False, codex_plugin=False, flow_panel=False)
    prefs["style"] = "uce" if ask(
        "Use the UCE reply style (emoji-led, very short, one thought per line)?",
        "Recommended by the author for skimming readers; it is a personal preference, say no for neutral replies.",
        True, auto) else "plain"
    prefs["git_hooks"] = ask("Install git hooks in this repo (auto-sync after pull, leak scan before push)?",
                             "Keeps the generated files fresh and stops private paths or tokens from being pushed.",
                             True, auto)
    prefs["set_env"] = ask("Set the SOCRATEX_HOME user environment variable?",
                           "Lets rules and skills find this folder from any project.", True, auto)
    prefs["subrepos"] = ask(
        "Download the reference packs (15 other agent toolkits: superpowers, pstack, ECC, spec-kit, ...)?",
        "Read-only copies (several hundred MB) kept OUTSIDE this repo and searched only when SocratexAI lacks a "
        "capability. Nothing from them is installed or run. Skip it and fetch later with modules/tools/scripts/subrepos.py update.",
        False, auto)
    if prefs["subrepos"]:
        prefs["refs_dir"] = ask_text("Folder for the reference packs:", str(Path.home() / "ai-refs"), auto)
    return prefs


# ---------- filesystem helpers ----------

def is_link(path: Path) -> bool:
    if path.is_symlink():
        return True
    isjunction = getattr(os.path, "isjunction", None)
    if isjunction:
        return isjunction(path)
    return path.exists() and os.path.realpath(path) != os.path.abspath(path)


def link_target(path: Path) -> Path | None:
    return Path(os.path.realpath(path)) if is_link(path) else None


def make_dir_link(link: Path, target: Path, report: list[str], check: bool) -> None:
    """Directory junction on Windows (no admin needed), symlink elsewhere. A real folder in the way is moved aside."""
    if is_link(link) and link_target(link) == target.resolve():
        return
    now = f" (now -> {link_target(link)})" if is_link(link) else " (replaces a real folder, moved aside first)" if link.exists() else ""
    report.append(f"link {link} -> {target}{now}")
    if check:
        return
    link.parent.mkdir(parents=True, exist_ok=True)
    if is_link(link):
        os.unlink(link) if link.is_symlink() else os.rmdir(link)
    elif link.exists():
        aside = HOME_DIR / "claude-backup" / "replaced" / link.parent.name / link.name
        aside.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(link), str(aside if not aside.exists() else aside.with_name(aside.name + "-old")))
    if os.name == "nt":
        subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)], check=True, capture_output=True)
    else:
        link.symlink_to(target, target_is_directory=True)


def write_if_changed(path: Path, text: str, report: list[str], check: bool) -> None:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return
    report.append(f"write {path}")
    if PLAN is not None:
        PLAN.append((path, old, text))
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


def strip_frontmatter(text: str) -> str:
    return re.sub(r"\A---\n.*?\n---\n+", "", text, count=1, flags=re.DOTALL)


# ---------- local profile ----------

def ensure_local(report: list[str], check: bool) -> None:
    example = SOCRATEX / "local.example"
    for source in example.glob("*"):
        target = LOCAL / source.name
        if not target.exists():
            report.append(f"create {target} from local.example")
            if not check:
                LOCAL.mkdir(exist_ok=True)
                shutil.copy2(source, target)


# ---------- Claude ----------

def styled(items: list[str]) -> list[str]:
    """Drop the reply-style document when the owner chose neutral replies."""
    return [item for item in items if PREFS["style"] == "uce" or item != STYLE_DOC]


def load_rules() -> bool:
    """Config key startup.load_rules (default true): whether defaults/RULES.md is part of the startup text."""
    import core
    return bool(core.resolve(None, SOCRATEX)["values"].get("startup", {}).get("load_rules", True))


def startup_items(items: list[str]) -> list[str]:
    """The documents of the startup entry; the reply style and defaults/RULES.md drop out when the owner or the config says so."""
    keep_rules = load_rules()
    return [item for item in styled(items) if keep_rules or item != RULES_DOC]


def extension_lines() -> list[str]:
    """Generated startup lines of the enabled extensions (config key `extensions`): a header and `name: when_to_use` each."""
    import core
    return core.extension_block(core.resolve(None, SOCRATEX)["values"], SOCRATEX)


def claude_block() -> str:
    items = startup_items(CLAUDE_IMPORTS)
    lines = [BEGIN,
             f"SOCRATEX_HOME = `{posix(SOCRATEX)}` (global AI core; index: `{posix(SOCRATEX / 'INDEX.json')}`).",
             "Do not edit this block: change the SocratexAI sources and rerun `sox install`.", ""]
    lines += [f"@{posix(SOCRATEX / item)}" for item in items]
    extensions = extension_lines()
    lines += [""] + extensions if extensions else []
    return generated.stamp("\n".join(lines + [END]), items + ["defaults/config.json", "modules/extensions"], at=1)


def install_claude_md(report: list[str], check: bool) -> None:
    path = CLAUDE / "CLAUDE.md"
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    block = claude_block()
    if BEGIN in old and END in old:
        new = old[: old.index(BEGIN)] + block + old[old.index(END) + len(END):]
    else:
        new = block + ("\n\n" + old if old.strip() else "\n")
    write_if_changed(path, new if new.endswith("\n") else new + "\n", report, check)


def install_claude_index(report: list[str], check: bool) -> None:
    path = CLAUDE / "INDEX.json"
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    indexes = [entry for entry in data.get("indexes", []) if entry.get("scope") != "socratex-core"]
    indexes.insert(0, {"scope": "socratex-core", "about": "Global AI core: rules, routing, agents, skills, tools, AI docs",
                       "index": posix(SOCRATEX / "INDEX.json")})
    data.update({
        "schema": "claude-index/v1",
        "purpose": "Global entry point. Only links to per-scope INDEX.json files; read this first when looking for a document, then open only the matching index.",
        "rules": [
            "Check this index before any grep/glob over the disk.",
            "Every project keeps its own INDEX.json in its root (relative paths). Create it when you start a project and add it to 'indexes' below.",
            "New document, skill, script or tool = add one entry to the nearest INDEX.json (path, what). Stale entry = fix or remove. No secrets in any index.",
        ],
        "indexes": indexes,
    })
    write_if_changed(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n", report, check)


def deep_merge(base: dict, extra: dict) -> dict:
    merged = dict(base)
    for key, value in extra.items():
        if key.startswith("_"):
            continue
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        elif isinstance(value, list) and isinstance(merged.get(key), list):
            merged[key] = merge_list(merged[key], value)
        else:
            merged[key] = value
    return merged


def merge_list(base: list, extra: list) -> list:
    """Union that replaces hook entries pointing at the SocratexAI guard instead of duplicating them."""
    result = [item for item in base if "claude/hooks/" not in json.dumps(item)]
    for item in extra:
        if item not in result:
            result.append(item)
    return result


def settings_fragment(python: str) -> dict:
    """The settings.json fragment for the chosen options (optional parts are dropped, never forced)."""
    text = (SOCRATEX / "claude" / "settings.json").read_text(encoding="utf-8")
    fragment = json.loads(text.replace("{SOCRATEX_HOME}", posix(SOCRATEX)).replace("{PYTHON}", python.replace("\\", "/"))
                               .replace("{REFS_DIR}", posix(refs_folder())))
    if not PREFS["codex_plugin"]:
        fragment.pop("extraKnownMarketplaces", None)
        fragment.pop("enabledPlugins", None)
    if not PREFS["flow_panel"]:
        fragment.get("env", {}).pop("CLAUDE_CODE_PLUGIN_DIRS", None)
    return fragment


def install_claude_settings(python: str, report: list[str], check: bool) -> None:
    if not PREFS["merge_settings"]:
        return
    path = CLAUDE / "settings.json"
    current = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    merged = deep_merge(current, settings_fragment(python))
    write_if_changed(path, json.dumps(merged, indent=2, ensure_ascii=False) + "\n", report, check)


def install_claude_links(report: list[str], check: bool) -> None:
    make_dir_link(CLAUDE / "agents", TARGETS / "claude" / "agents", report, check)
    for folder in (SHARED_SKILLS, CLAUDE_SKILLS):
        for skill in sorted(p for p in folder.iterdir() if (p / "SKILL.md").exists()):
            make_dir_link(CLAUDE / "skills" / skill.name, skill, report, check)


# ---------- Codex ----------

def codex_agents_md() -> str:
    header = [f"SOCRATEX_HOME = `{posix(SOCRATEX)}` (global AI core; index: `{posix(SOCRATEX / 'INDEX.json')}`).",
              "Do not edit this file: change the SocratexAI sources and rerun `sox install`.", ""]
    items = [part for part in startup_items(CODEX_PARTS) if (SOCRATEX / part).exists()]
    parts = [strip_frontmatter((SOCRATEX / part).read_text(encoding="utf-8")).strip() for part in items]
    extensions = extension_lines()
    parts += ["\n".join(extensions)] if extensions else []
    return generated.stamp("\n".join(header) + "\n" + "\n\n".join(parts) + "\n", items + ["defaults/config.json", "modules/extensions"])


def codex_agent_toml(name: str, tier: str, routing: dict) -> str:
    spec = routing["codex"][tier]
    purpose = {"cheap": "Simple, fully specified, low-risk work with an easy check.",
               "standard": "Well-defined feature work, typical fixes and bounded refactors from a clear spec.",
               "high": "Planning, review, uncertain or coupled work and escalations."}[tier]
    if name.endswith("reviewer"):
        purpose = "Independent review of a diff against its spec and the project standard; read-only, returns verdict, defects, risks."
    return (f'name = "{name}"\n'
            f'description = "{purpose}"\n'
            f'model = "{spec["model"]}"\n'
            f'model_reasoning_effort = "{spec["effort"]}"\n'
            'developer_instructions = """\n'
            "Follow the project's AGENTS.md and $SOCRATEX_HOME/defaults/RULES.md. Respect the parent's exact scope,\n"
            "ownership, approvals and checks. Escalate ambiguity or failed attempts with evidence instead of\n"
            "repeating weak approaches. Report changes, verification and residual uncertainty in the owner's\n"
            "configured language. Do not delegate further, commit, push, finalize or mark tasks complete.\n"
            '"""\n')


def install_codex(report: list[str], check: bool) -> None:
    write_if_changed(CODEX / "AGENTS.md", codex_agents_md(), report, check)
    routing = json.loads((SOCRATEX / "defaults" / "ROUTING.json").read_text(encoding="utf-8"))
    for name, tier in routing["codex_agents"].items():
        write_if_changed(CODEX / "agents" / f"{name}.toml", codex_agent_toml(name, tier, routing), report, check)
    for skill in sorted(p for p in SHARED_SKILLS.iterdir() if (p / "SKILL.md").exists()):
        make_dir_link(CODEX / "skills" / skill.name, skill, report, check)
    install_codex_env(report, check)


def install_codex_env(report: list[str], check: bool) -> None:
    path = CODEX / "config.toml"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    line = f'SOCRATEX_HOME = "{posix(SOCRATEX)}"'
    if re.search(r"(?m)^SOCRATEX_HOME\s*=.*$", text):
        new = re.sub(r"(?m)^SOCRATEX_HOME\s*=.*$", line, text)
    elif "[shell_environment_policy.set]" in text:
        new = text.replace("[shell_environment_policy.set]", "[shell_environment_policy.set]\n" + line, 1)
    else:
        new = text.rstrip("\n") + "\n\n[shell_environment_policy.set]\n" + line + "\n"
    write_if_changed(path, new, report, check)


# ---------- machine ----------

def current_user_env(name: str) -> str:
    """The persisted user value; setx does not change the environment of running processes."""
    if os.name != "nt":
        return os.environ.get(name, "")
    import winreg
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment") as key:
            return str(winreg.QueryValueEx(key, name)[0])
    except OSError:
        return ""


def install_env(report: list[str], check: bool) -> None:
    if not PREFS["set_env"]:
        return
    if current_user_env("SOCRATEX_HOME").replace("\\", "/") == posix(SOCRATEX):
        return
    report.append(f"set user env SOCRATEX_HOME={posix(SOCRATEX)}")
    if check:
        return
    if os.name == "nt":
        subprocess.run(["setx", "SOCRATEX_HOME", posix(SOCRATEX)], check=True, capture_output=True)
    else:
        report.append("  add to your shell profile: export SOCRATEX_HOME=" + posix(SOCRATEX))


def refs_folder() -> Path:
    """Where the reference packs live: the saved choice, else SOCRATEX_REFS / ~/ai-refs."""
    if PREFS.get("refs_dir"):
        return Path(PREFS["refs_dir"])
    import subrepos
    return subrepos.refs_dir()


def install_subrepos(mode: str, report: list[str]) -> None:
    """Download the reference packs once, on a full install the owner agreed to. Never on --sync or --check:
    updating packs is the separate, on-request `modules/tools/scripts/update.py refs`."""
    if mode != "full" or not PREFS["subrepos"]:
        return
    import subrepos
    os.environ["SOCRATEX_REFS"] = str(refs_folder())
    if subrepos.cmd_update([]):
        report.append("note: some reference packs failed to download; rerun `python modules/tools/scripts/update.py refs`")


def install_git_hooks(python: str, report: list[str], check: bool) -> None:
    if not PREFS["git_hooks"]:
        return
    hooks = SOCRATEX / ".git" / "hooks"
    if not hooks.exists():
        return
    py = python.replace("\\", "/")
    scripts = {
        "post-merge": f'#!/bin/sh\n"{py}" -B "$(git rev-parse --show-toplevel)/modules/tools/scripts/install.py" --sync\n',
        "pre-push": f'#!/bin/sh\n"{py}" -B "$(git rev-parse --show-toplevel)/modules/tools/scripts/check_leaks.py"\n',
    }
    for name, body in scripts.items():
        write_if_changed(hooks / name, body, report, check)


# ---------- entry ----------

def resolve_prefs(mode: str, auto: bool, reconfigure: bool) -> bool:
    """Load or collect the answers. Returns False when a full install cannot ask (no terminal, no --yes)."""
    saved = load_prefs()
    if mode != "full":
        apply_prefs(saved or {})  # older installs without answers keep their original behaviour
        return True
    if saved is not None and not reconfigure:
        apply_prefs(saved)
        return True
    if not auto and not sys.stdin.isatty():
        print("Full install asks questions first. Run it in a terminal, or pass --yes to accept the recommended answers.")
        return False
    apply_prefs(collect_prefs(auto))
    return True


def install_steps(python: str, report: list[str], check: bool, mode: str = "check") -> None:
    """Every step that touches the agent config folders; with check=True nothing is written (reports and PLAN only)."""
    ensure_local(report, check)
    if PREFS["claude"]:
        install_claude_md(report, check)
        install_claude_index(report, check)
        install_claude_settings(python, report, check)
        install_claude_links(report, check)
        if not PREFS["merge_settings"]:
            report.append("note: settings.json untouched, so the guard hook is not active")
    if PREFS["codex"]:
        install_codex(report, check)
    install_env(report, check)
    install_git_hooks(python, report, check)
    install_subrepos(mode, report)


def collect_plan(target: str | None = None) -> tuple[list[str], list[tuple[Path, str | None, str]]]:
    """Dry run of a full install: report lines plus (path, current text, new text) per file that would change.
    Generates targets/ (inside the repo) and only reads the agent config folders."""
    global PLAN
    import targets
    apply_prefs(load_prefs() or {})
    if target:
        PREFS["claude"], PREFS["codex"] = target == "claude" and PREFS["claude"], target == "codex" and PREFS["codex"]
    targets.generate(target)
    report: list[str] = []
    PLAN = []
    try:
        install_steps(sys.executable, report, True)
        return report, list(PLAN)
    finally:
        PLAN = None


def run(mode: str, auto: bool = False, reconfigure: bool = False) -> int:
    check = mode == "check"
    report: list[str] = []
    if not resolve_prefs(mode, auto, reconfigure):
        return 2
    if mode == "sync" and not PREFS["targets_applied"]:
        print("SocratexAI: the generated startup entry is not applied yet; run `sox install --plan`, then `sox install --yes`.")
        return 0
    if mode == "full" or (mode == "sync" and not PREFS_FILE.exists()):
        save_prefs()
    if mode == "full":
        import backup
        print(f"Backup: {backup.backup('pre-install')}")
    if not check:
        import targets
        targets.generate()
    install_steps(sys.executable, report, check, mode)
    if check:
        print("SocratexAI install is up to date." if not report else "Missing or stale:\n  " + "\n  ".join(report))
        return 1 if report else 0
    if mode == "full":
        PREFS["targets_applied"] = True
        save_prefs()
    if report or mode == "full":
        print("SocratexAI installed:" if report else "SocratexAI: nothing to change.")
        for line in report:
            print("  " + line)
    if mode == "full":
        print_suggested_mods()
    return 0


