from pathlib import Path

HOME_DIR = Path.home()
SOCRATEX = Path(__file__).resolve().parents[3]
LOCAL = SOCRATEX / "local"
PREFS_FILE = LOCAL / "install.json"
BEGIN, END = "<!-- socratex:begin (generated by SocratexAI modules/tools/scripts/install.py) -->", "<!-- socratex:end -->"
RULES_DOC = "defaults/RULES.md"
# Startup entry: the initializer, the reply style, the adapter file of the agent and the owner profile.
# defaults/RULES.md joins only while the config key startup.load_rules is true (transitional, see startup_items).
CLAUDE_IMPORTS = ["core/INIT.md", RULES_DOC, "defaults/STYLE.md", "claude/CLAUDE.md", "local/profile.md"]
CODEX_PARTS = ["core/INIT.md", RULES_DOC, "defaults/STYLE.md", "codex/AGENTS.md", "local/profile.md"]
TARGETS = SOCRATEX / "targets"
SHARED_SKILLS = SOCRATEX / "skills"
CLAUDE_SKILLS = SOCRATEX / "claude" / "skills"
STYLE_DOC = "defaults/STYLE.md"

# Answers of the install questions. Defaults reproduce the original full install; the wizard narrows them.
PREF_DEFAULTS = {"claude": True, "codex": True, "merge_settings": True, "codex_plugin": True, "flow_panel": True,
                 "style": "uce", "git_hooks": True, "set_env": True, "subrepos": False, "refs_dir": "", "claude_dir": "", "codex_dir": "",
                 "targets_applied": False}
PREFS = dict(PREF_DEFAULTS)
CLAUDE = HOME_DIR / ".claude"
CODEX = HOME_DIR / ".codex"

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(SOCRATEX / "core"))

