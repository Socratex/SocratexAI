#!/usr/bin/env python3
"""Install SocratexAI as the global AI core for Claude Code and Codex on this machine.

Idempotent: run it after cloning, and it runs itself after every `git pull` (post-merge hook).
Nothing is changed without the owner's yes: a full install asks (with the reason) before touching
settings.json, enabling the Codex plugin, the flow panel, git hooks or the SOCRATEX_HOME variable, and offers the
UCE reply style as a recommendation. Answers are saved in local/install.json (gitignored) and reused by --sync.
What it does:
  1. Backs up the global agent config (modules/tools/scripts/backup.py) - full install only.
  2. Creates local/ from local.example/ when missing (private profile, never committed).
  3. Claude: managed block in ~/.claude/CLAUDE.md (imports the initializer, reply style, adapter and local profile;
     defaults/RULES.md only while config startup.load_rules is true), ~/.claude/INDEX.json, junctions ~/.claude/agents
     (to the generated targets/claude/agents) and ~/.claude/skills/<name>, settings fragment merged into ~/.claude/settings.json.
  4. Codex: generates ~/.codex/AGENTS.md, ~/.codex/agents/socratex_*.toml, junctions ~/.codex/skills/<name>,
     SOCRATEX_HOME in ~/.codex/config.toml.
  5. Sets the SOCRATEX_HOME user environment variable and installs the repo git hooks.

Generated files (targets/, gitignored) carry a marker header `GENERATED by sox install from <sources>; hash=...`
(modules/tools/scripts/generated.py). The owner-facing entry is `sox install --plan | --check | --yes` (core/sox, core/targets.py);
--sync stays inactive until the first approved apply (`local/install.json`: targets_applied).

Usage:
    python modules/tools/scripts/install.py            # full install (asks first, then backs up)
    python modules/tools/scripts/install.py --yes      # full install, accept every recommended answer (no questions)
    python modules/tools/scripts/install.py --reconfigure   # ask the questions again
    python modules/tools/scripts/install.py --sync     # regenerate after a pull (no backup, quiet)
    python modules/tools/scripts/install.py --check    # report what is missing or stale, change nothing
"""

from __future__ import annotations

import argparse
import json
